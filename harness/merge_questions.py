#!/usr/bin/env python3
"""Merge questions/parts/*.yaml into questions/questions.yaml and print coverage counts.

    .venv/bin/python -I harness/merge_questions.py            # merge + counts
    .venv/bin/python -I harness/merge_questions.py --check    # exit 1 if questions.yaml is stale
    .venv/bin/python -I harness/merge_questions.py --counts-md build/question_counts.md

The part files are the source; questions.yaml is generated (one list, parts in a fixed group
order, questions in file order). Ids must be unique across parts.
"""
from __future__ import annotations

import argparse
import collections
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import yaml  # noqa: E402

PARTS = ROOT / "questions" / "parts"
OUT = ROOT / "questions" / "questions.yaml"
GROUP_ORDER = ["long", "vis", "str", "txt", "trap", "hop", "code", "guard"]
HEADER = (
    "# GENERATED by harness/merge_questions.py from questions/parts/*.yaml. Edit the parts, then re-run.\n"
    "# Format: docs/CONVENTIONS.md section 7. Categories: questions/CATEGORIES.md.\n"
)


class _Dumper(yaml.SafeDumper):
    pass


def _str_rep(dumper, s):
    style = "|" if "\n" in s else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style=style)


_Dumper.add_representer(str, _str_rep)


def load_parts() -> tuple[list[dict], list[str]]:
    files = sorted(PARTS.glob("*.y*ml"), key=lambda p: (GROUP_ORDER.index(p.stem) if p.stem in GROUP_ORDER else 99, p.stem))
    qs: list[dict] = []
    for f in files:
        d = yaml.safe_load(f.read_text(encoding="utf-8-sig")) or []
        d = d.get("questions", []) if isinstance(d, dict) else d
        if not isinstance(d, list):
            sys.exit(f"{f.name}: top level must be a list")
        qs.extend(d)
    return qs, [f.name for f in files]


def counts(qs: list[dict]) -> dict[str, collections.Counter]:
    c = {k: collections.Counter() for k in ("category", "group", "ask_mode", "difficulty", "hops", "variant", "dimension")}
    for q in qs:
        c["category"][q.get("category", "?")] += 1
        qid = str(q.get("id", ""))
        c["group"][qid.split("-")[1] if qid.count("-") >= 2 else "?"] += 1
        c["ask_mode"][q.get("ask_mode", "?")] += 1
        c["difficulty"][q.get("difficulty", "?")] += 1
        c["hops"][int(q.get("hops") or 0)] += 1
        if q.get("variant"):
            c["variant"][q["variant"]] += 1
        for d in q.get("dimensions") or []:
            c["dimension"][d] += 1
    return c


def counts_md(qs: list[dict]) -> str:
    c = counts(qs)
    out = [f"**{len(qs)} questions.**", ""]
    for key in ("category", "ask_mode", "hops", "difficulty", "variant", "group"):
        out += [f"| {key} | questions |", "|---|---|"]
        items = sorted(c[key].items(), key=lambda kv: (str(kv[0]) if key == "hops" else -kv[1], str(kv[0])))
        if key == "hops":
            items = sorted(c[key].items())
        out += [f"| {k} | {v} |" for k, v in items]
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--counts-md", help="also write the coverage tables as Markdown to this path")
    a = ap.parse_args()
    qs, files = load_parts()
    ids = collections.Counter(q.get("id") for q in qs)
    dup = [i for i, n in ids.items() if n > 1 or not i]
    if dup:
        print(f"duplicate or missing ids: {dup}", file=sys.stderr)
        return 1
    text = HEADER + yaml.dump(qs, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("questions.yaml is up to date" if ok else "questions.yaml is STALE: re-run harness/merge_questions.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(qs)} questions from {len(files)} parts ({', '.join(files)})")
    md = counts_md(qs)
    if a.counts_md:
        p = pathlib.Path(a.counts_md)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(md + "\n", encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
