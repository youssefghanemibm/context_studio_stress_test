-- --------------------------------------------------------------------
-- CLR.T_RESERVE_MOVEMENT
-- Audit trail of reserve changes; source of CLX-IF-042
-- Area: RESERVE    Copybook: RSVMVT01
-- --------------------------------------------------------------------
CREATE TABLE CLR.T_RESERVE_MOVEMENT
  ( MOVE_ID                     BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY
  , RSV_ID                      BIGINT        NOT NULL
  , CLAIM_ID                    CHAR(12)      NOT NULL
  , MOVE_TS                     TIMESTAMP     NOT NULL
  , MOVE_TYPE_CD                CHAR(2)       NOT NULL
  , MOVE_AMT                    DECIMAL(13,2) NOT NULL
  , MOVE_GBP_AMT                DECIMAL(13,2) NOT NULL
  , REASON_CD                   CHAR(4)       NOT NULL
  , USER_ID                     CHAR(8)       NOT NULL
  , PGM_ID                      CHAR(8)       NOT NULL
  , EXTRACTED_FLAG              CHAR(1)       NOT NULL
  , EXTRACT_RUN_ID              INTEGER
  , CONSTRAINT PK_T_RESERVE_MOVEMENT PRIMARY KEY (MOVE_ID)
  )
  CCSID EBCDIC;

CREATE UNIQUE INDEX CLR.XRESERVE_MOVEME_PK
    ON CLR.T_RESERVE_MOVEMENT (MOVE_ID);
CREATE INDEX CLR.XRESERVE_MOVEM_CLM
    ON CLR.T_RESERVE_MOVEMENT (CLAIM_ID);

ALTER TABLE CLR.T_RESERVE_MOVEMENT
  ADD CONSTRAINT FK_RESERVE_MOVE_1 FOREIGN KEY (RSV_ID)
      REFERENCES CLR.T_RESERVE (RSV_ID) ON DELETE RESTRICT;

ALTER TABLE CLR.T_RESERVE_MOVEMENT
  ADD CONSTRAINT FK_RESERVE_MOVE_2 FOREIGN KEY (CLAIM_ID)
      REFERENCES CLR.T_CLAIM (CLAIM_ID) ON DELETE RESTRICT;

COMMENT ON TABLE CLR.T_RESERVE_MOVEMENT IS
  'Audit trail of reserve changes; source of CLX-IF-042';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.MOVE_ID IS
  'Movement identifier';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.RSV_ID IS
  'Reserve identifier (FK CLR.T_RESERVE)';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.CLAIM_ID IS
  'Claim reference';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.MOVE_TS IS
  'Movement timestamp';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.MOVE_TYPE_CD IS
  'IN initial, AD adjustment, IX indexation, RV review, ST settlement close, RC recovery';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.MOVE_AMT IS
  'Movement amount in reserve currency';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.MOVE_GBP_AMT IS
  'Movement amount in GBP';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.REASON_CD IS
  'Reason code';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.USER_ID IS
  'User or batch id';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.PGM_ID IS
  'Program that created the movement';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.EXTRACTED_FLAG IS
  'Y once extracted by CLRRS170 for CLX-IF-042';
COMMENT ON COLUMN CLR.T_RESERVE_MOVEMENT.EXTRACT_RUN_ID IS
  'CLX-IF-042 extract run id';
