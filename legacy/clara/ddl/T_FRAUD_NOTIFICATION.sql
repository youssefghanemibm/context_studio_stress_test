CREATE TABLE CLR.T_FRAUD_NOTIFICATION
  ( NOTICE_ID                   BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY
  , REF_ID                      BIGINT        NOT NULL
  , CLAIM_ID                    CHAR(12)      NOT NULL
  , NOTICE_CHANNEL_CD           CHAR(2)       NOT NULL
  , NOTICE_DUE_DT               DATE          NOT NULL
  , NOTICE_SENT_TS              TIMESTAMP
  , DEFERRED_UNTIL_DT           DATE
  , TEMPLATE_CD                 CHAR(8)       NOT NULL
  , NOTIFY_MSG_ID               CHAR(36)
  , LAST_UPD_TS                 TIMESTAMP     NOT NULL WITH DEFAULT
  , LAST_UPD_PGM                CHAR(8)       NOT NULL
  , LAST_UPD_USER               CHAR(8)       NOT NULL
  , CONSTRAINT PK_T_FRAUD_NOTIFICATION PRIMARY KEY (NOTICE_ID)
  )
  CCSID EBCDIC;

CREATE UNIQUE INDEX CLR.XFRAUD_NOTIFICA_PK
    ON CLR.T_FRAUD_NOTIFICATION (NOTICE_ID);
CREATE INDEX CLR.XFRAUD_NOTIFIC_CLM
    ON CLR.T_FRAUD_NOTIFICATION (CLAIM_ID);

ALTER TABLE CLR.T_FRAUD_NOTIFICATION
  ADD CONSTRAINT FK_FRAUD_NOTIFI_1 FOREIGN KEY (REF_ID)
      REFERENCES CLR.T_FRAUD_REFERRAL (REF_ID) ON DELETE RESTRICT;

COMMENT ON TABLE CLR.T_FRAUD_NOTIFICATION IS
  'Customer notices of fraud referral (NISA Circular 2026/04); created 2026-03-27';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.NOTICE_ID IS
  'Notice identifier';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.REF_ID IS
  'Referral identifier';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.CLAIM_ID IS
  'Claim reference';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.NOTICE_CHANNEL_CD IS
  'LT letter, SM SMS, EM email';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.NOTICE_DUE_DT IS
  'Due date';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.NOTICE_SENT_TS IS
  'Sent timestamp';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.DEFERRED_UNTIL_DT IS
  'Deferred until (max 60 days)';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.TEMPLATE_CD IS
  'Notify template code';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.NOTIFY_MSG_ID IS
  'Notify message id';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.LAST_UPD_TS IS
  'Timestamp of last update';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.LAST_UPD_PGM IS
  'Program that last updated the row';
COMMENT ON COLUMN CLR.T_FRAUD_NOTIFICATION.LAST_UPD_USER IS
  'User or batch id that last updated the row';
