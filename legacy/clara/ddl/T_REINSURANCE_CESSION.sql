-- --------------------------------------------------------------------
-- CLR.T_REINSURANCE_CESSION
-- Reinsurance cessions
-- Area: GL    Copybook: RICESS01
-- --------------------------------------------------------------------
CREATE TABLE CLR.T_REINSURANCE_CESSION
  ( CESSION_ID                  BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY
  , CLAIM_ID                    CHAR(12)      NOT NULL
  , TREATY_CD                   CHAR(8)       NOT NULL
  , CEDED_RSV_AMT               DECIMAL(13,2) NOT NULL
  , CEDED_PAID_AMT              DECIMAL(13,2) NOT NULL
  , REINSURER_CD                CHAR(8)       NOT NULL
  , LAST_UPD_TS                 TIMESTAMP     NOT NULL WITH DEFAULT
  , LAST_UPD_PGM                CHAR(8)       NOT NULL
  , LAST_UPD_USER               CHAR(8)       NOT NULL
  , CONSTRAINT PK_T_REINSURANCE_CESSION PRIMARY KEY (CESSION_ID)
  )
  CCSID EBCDIC;

CREATE UNIQUE INDEX CLR.XREINSURANCE_CE_PK
    ON CLR.T_REINSURANCE_CESSION (CESSION_ID);
CREATE INDEX CLR.XREINSURANCE_C_CLM
    ON CLR.T_REINSURANCE_CESSION (CLAIM_ID);

COMMENT ON TABLE CLR.T_REINSURANCE_CESSION IS
  'Reinsurance cessions';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.CESSION_ID IS
  'Cession id';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.CLAIM_ID IS
  'Claim reference';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.TREATY_CD IS
  'Treaty';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.CEDED_RSV_AMT IS
  'Ceded reserve';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.CEDED_PAID_AMT IS
  'Ceded paid';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.REINSURER_CD IS
  'Reinsurer';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.LAST_UPD_TS IS
  'Timestamp of last update';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.LAST_UPD_PGM IS
  'Program that last updated the row';
COMMENT ON COLUMN CLR.T_REINSURANCE_CESSION.LAST_UPD_USER IS
  'User or batch id that last updated the row';
