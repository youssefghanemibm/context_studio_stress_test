-- --------------------------------------------------------------------
-- CLR.T_RESERVE_AUTHORITY
-- Reserve approvals above authority (BR-RSV-003)
-- Area: RESERVE    Copybook: RSVAUT01
-- --------------------------------------------------------------------
CREATE TABLE CLR.T_RESERVE_AUTHORITY
  ( AUTH_ID                     BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY
  , RSV_ID                      BIGINT        NOT NULL
  , REQUESTED_AMT               DECIMAL(13,2) NOT NULL
  , REQUIRED_LEVEL              CHAR(2)       NOT NULL
  , APPROVER_USER               CHAR(8)
  , DECISION_CD                 CHAR(2)       NOT NULL
  , LAST_UPD_TS                 TIMESTAMP     NOT NULL WITH DEFAULT
  , LAST_UPD_PGM                CHAR(8)       NOT NULL
  , LAST_UPD_USER               CHAR(8)       NOT NULL
  , CONSTRAINT PK_T_RESERVE_AUTHORITY PRIMARY KEY (AUTH_ID)
  )
  CCSID EBCDIC;

CREATE UNIQUE INDEX CLR.XRESERVE_AUTHOR_PK
    ON CLR.T_RESERVE_AUTHORITY (AUTH_ID);

ALTER TABLE CLR.T_RESERVE_AUTHORITY
  ADD CONSTRAINT FK_RESERVE_AUTH_1 FOREIGN KEY (RSV_ID)
      REFERENCES CLR.T_RESERVE (RSV_ID) ON DELETE RESTRICT;

COMMENT ON TABLE CLR.T_RESERVE_AUTHORITY IS
  'Reserve approvals above authority (BR-RSV-003)';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.AUTH_ID IS
  'Approval id';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.RSV_ID IS
  'Reserve id';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.REQUESTED_AMT IS
  'Requested';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.REQUIRED_LEVEL IS
  'Required level';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.APPROVER_USER IS
  'Approver';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.DECISION_CD IS
  'AP, RJ, PD';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.LAST_UPD_TS IS
  'Timestamp of last update';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.LAST_UPD_PGM IS
  'Program that last updated the row';
COMMENT ON COLUMN CLR.T_RESERVE_AUTHORITY.LAST_UPD_USER IS
  'User or batch id that last updated the row';
